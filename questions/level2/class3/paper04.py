def tri_cross():
    """Triangle with one line from the top corner and one line across."""
    return [('poly', [(110, 10), (10, 150), (210, 150)], 'pink'), ('line', 110, 10, 130, 150), ('line', 53, 90, 167, 90)]


def strip12():
    s = 26
    return [('rect', 10 + k * s, 10, s, s, 'blue' if k < 3 else 'white') for k in range(12)]


