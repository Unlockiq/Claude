def grid3():
    s = 36
    prims = [('rect', 10, 10, 3 * s, 3 * s, 'blue')]
    for k in (1, 2):
        prims += [('line', 10 + k * s, 10, 10 + k * s, 10 + 3 * s), ('line', 10, 10 + k * s, 10 + 3 * s, 10 + k * s)]
    return prims


