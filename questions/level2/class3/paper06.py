def ring_square():
    s = 34
    prims = []
    for r in range(3):
        for c in range(3):
            if (r, c) != (1, 1):
                prims.append(('rect', 10 + c * s, 10 + r * s, s, s, 'yellow'))
    prims.append(('text', 10 + 1.5 * s, 2, '2 cm each', 10))
    return prims


