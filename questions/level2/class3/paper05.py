def plus_shape():
    s = 30
    pts = [(s, 0), (2 * s, 0), (2 * s, s), (3 * s, s), (3 * s, 2 * s), (2 * s, 2 * s), (2 * s, 3 * s), (s, 3 * s), (s, 2 * s),
           (0, 2 * s), (0, s), (s, s)]
    return [('poly', [(x + 10, y + 10) for x, y in pts], 'green')]


