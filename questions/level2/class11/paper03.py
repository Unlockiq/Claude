def plane(x0, x1, y0, y1, u=22, segs=(), pts=(), labels=()):
    X = lambda x: (x - x0) * u
    Y = lambda y: (y1 - y) * u
    prims = [('line', X(x0), Y(0), X(x1), Y(0)), ('line', X(0), Y(y0), X(0), Y(y1)),
             ('text', X(x1) + 8, Y(0), 'x', 11), ('text', X(0), Y(y1) - 9, 'y', 11), ('text', X(0) - 9, Y(0) + 9, 'O', 10)]
    for a, b, c, d in segs:
        prims.append(('line', X(a), Y(b), X(c), Y(d)))
    for a, b, name in pts:
        prims += [('dot', X(a), Y(b), 3.5), ('text', X(a) + 14, Y(b) - 9, name, 10)]
    for s, a, b in labels:
        prims.append(('text', X(a), Y(b), s, 10))
    return prims


