def dot_grid(n=3, s=40):
    return [('dot', 10 + c * s, 10 + r * s, 4.5) for r in range(n) for c in range(n)]


def five_dots():
    import math
    return [('dot', 60 + 50 * math.cos(math.radians(90 + 72 * k)), 60 - 50 * math.sin(math.radians(90 + 72 * k)), 5) for k in range(5)]


def tiles(n, x0, s=10):
    prims = []
    for r in range(n):
        for c in range(n):
            prims.append(('rect', x0 + c * s, 70 - n * s + r * s, s, s, 'blue'))
    return prims


