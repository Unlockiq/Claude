def hexagram():
    import math
    up = [(80 + 62 * math.cos(math.radians(-90 + 120 * k)), 80 + 62 * math.sin(math.radians(-90 + 120 * k))) for k in range(3)]
    dn = [(80 + 62 * math.cos(math.radians(90 + 120 * k)), 80 + 62 * math.sin(math.radians(90 + 120 * k))) for k in range(3)]
    return [('poly', up, 'pink'), ('poly', dn, None)]


