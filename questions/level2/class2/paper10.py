def square_star():
    return [('rect', 10, 10, 120, 120, 'yellow'), ('line', 10, 10, 130, 130), ('line', 130, 10, 10, 130),
            ('line', 70, 10, 70, 130), ('line', 10, 70, 130, 70)]


def tri3(s=40):
    import math
    h = s * math.sqrt(3) / 2
    prims = [('poly', [(10 + 1.5 * s, 10), (10, 10 + 3 * h), (10 + 3 * s, 10 + 3 * h)], 'green')]
    for r in (1, 2):
        y = 10 + r * h
        prims.append(('line', 10 + 1.5 * s - r * s / 2, y, 10 + 1.5 * s + r * s / 2, y))
    # lines parallel to the two slanting sides
    for k in (1, 2):
        prims.append(('line', 10 + k * s, 10 + 3 * h, 10 + k * s / 2, 10 + 3 * h - k * h))
        prims.append(('line', 10 + 3 * s - k * s, 10 + 3 * h, 10 + 3 * s - k * s / 2, 10 + 3 * h - k * h))
    return prims


