def tri_mid_two_across():
    # apex (110, 10), base from (10, 160) to (210, 160); one line from the apex, two lines across
    def at(y):
        t = (y - 10) / 150
        return 110 - 100 * t, 110 + 100 * t
    l1, r1 = at(60)
    l2, r2 = at(110)
    return [('poly', [(110, 10), (10, 160), (210, 160)], 'yellow'), ('line', 110, 10, 110, 160),
            ('line', l1, 60, r1, 60), ('line', l2, 110, r2, 110)]


def dot4():
    return [('dot', 10 + c * 36, 10 + r * 36, 4.5) for r in range(4) for c in range(4)]


