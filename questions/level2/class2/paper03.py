def grid4():
    s = 26
    prims = [('rect', 5, 5, 4 * s, 4 * s, 'yellow')]
    for k in range(1, 4):
        prims += [('line', 5 + k * s, 5, 5 + k * s, 5 + 4 * s), ('line', 5, 5 + k * s, 5 + 4 * s, 5 + k * s)]
    return prims


def pizza(n, cx, label):
    import math
    prims = [('circle', cx, 40, 32, 'peach')]
    for k in range(n):
        a = math.pi * k / n
        prims.append(('line', cx - 32 * math.cos(a), 40 - 32 * math.sin(a), cx + 32 * math.cos(a), 40 + 32 * math.sin(a)))
    prims.append(('text', cx, 88, label, 10))
    return prims


