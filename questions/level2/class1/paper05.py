def tri_strip(n, x0, s=30):
    h = 26
    prims = []
    for i in range(n):
        if i % 2 == 0:
            x = x0 + (i // 2) * s
            prims.append(('poly', [(x, h), (x + s / 2, 0), (x + s, h)], 'pink'))
        else:
            x = x0 + (i // 2) * s
            prims.append(('poly', [(x + s / 2, 0), (x + 1.5 * s, 0), (x + s, h)], 'white'))
    return prims


