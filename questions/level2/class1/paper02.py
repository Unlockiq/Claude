def tri_strip(n, x0, y0=0, s=30):
    """Strip of 2n-1 small triangles (n pointing up) starting at x0."""
    h = 26
    prims = []
    for i in range(n):
        x = x0 + i * s
        prims.append(('poly', [(x, y0 + h), (x + s / 2, y0), (x + s, y0 + h)], 'pink'))
        if i < n - 1:
            prims.append(('poly', [(x + s / 2, y0), (x + 1.5 * s, y0), (x + s, y0 + h)], 'white'))
    return prims


