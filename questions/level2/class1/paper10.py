import math


def tri_pyramid(side=60, top=(90, 5)):
    """Big triangle made of 9 small triangles (3 rows)."""
    h = side * 0.866
    prims = []
    for r in range(3):
        for k in range(r + 1):
            x, y = top[0] - side / 2 * r + side * k, top[1] + h * r
            prims.append(('poly', [(x, y), (x + side / 2, y + h), (x - side / 2, y + h)], 'pink'))
        for k in range(r):
            x, y = top[0] - side / 2 * r + side * k, top[1] + h * r
            prims.append(('poly', [(x, y), (x + side, y), (x + side / 2, y + h)], 'white'))
    return prims


def hexagon_fan(cx=80, cy=75, r=70):
    pts = [(cx + r * math.cos(math.radians(a)), cy + r * math.sin(math.radians(a))) for a in range(0, 360, 60)]
    return [('poly', [(cx, cy), pts[i], pts[(i + 1) % 6]], 'yellow' if i % 2 == 0 else 'peach') for i in range(6)]


