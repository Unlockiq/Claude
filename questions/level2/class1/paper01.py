def stick_row(n, x0=0, gap=40, s=30):
    """n squares in a row made of matchsticks, starting at x0."""
    segs = []
    for i in range(n):
        x = x0 + i * s
        segs += [((x, 0), (x + s, 0)), ((x, s), (x + s, s))]
        if i == 0:
            segs.append(((x, 0), (x, s)))
        segs.append(((x + s, 0), (x + s, s)))
    return segs


