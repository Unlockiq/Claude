def ten_frame(x, y, n, s=16):
    """A 2 x 5 ten-frame at (x, y) with n dots."""
    prims = [('rect', x, y, 5 * s, 2 * s, 'white')]
    for k in range(1, 5):
        prims.append(('line', x + k * s, y, x + k * s, y + 2 * s))
    prims.append(('line', x, y + s, x + 5 * s, y + s))
    for i in range(n):
        r, c = divmod(i, 5)
        prims.append(('dot', x + c * s + s / 2, y + r * s + s / 2, 5))
    return prims


def square_grid(x, y, n, s=18):
    prims = [('rect', x, y, n * s, n * s, 'yellow')]
    for k in range(1, n):
        prims += [('line', x + k * s, y, x + k * s, y + n * s), ('line', x, y + k * s, x + n * s, y + k * s)]
    return prims


