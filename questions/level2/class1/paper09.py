def tri_sticks(n, x0, s=30):
    """Segments for a strip of n triangles made of sticks (3, 5, 7, ... sticks)."""
    h = 26
    pts = []
    for i in range(n + 2):
        if i % 2 == 0:
            pts.append((x0 + (i // 2) * s, h))
        else:
            pts.append((x0 + (i // 2) * s + s / 2, 0))
    pts = pts[:n + 2]
    segs = [(pts[i], pts[i + 1]) for i in range(len(pts) - 1)]
    bottoms = [p for p in pts if p[1] == h]
    tops = [p for p in pts if p[1] == 0]
    segs += [(bottoms[i], bottoms[i + 1]) for i in range(len(bottoms) - 1)]
    segs += [(tops[i], tops[i + 1]) for i in range(len(tops) - 1)]
    return segs


