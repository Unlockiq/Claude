def tri_mid():
    A, B, C = (110, 10), (10, 170), (230, 170)
    D = ((A[0] + B[0]) / 2, (A[1] + B[1]) / 2)
    E = ((A[0] + C[0]) / 2, (A[1] + C[1]) / 2)
    return [('poly', [A, B, C], 'yellow'), ('line', D[0], D[1], E[0], E[1]),
            ('text', A[0], A[1] - 12, 'A', 12), ('text', B[0] - 10, B[1] + 8, 'B', 12), ('text', C[0] + 10, C[1] + 8, 'C', 12),
            ('text', D[0] - 12, D[1], 'D', 12), ('text', E[0] + 12, E[1], 'E', 12),
            ('text', (D[0] + E[0]) / 2, D[1] - 9, '7', 11), ('text', (A[0] + E[0]) / 2 + 12, (A[1] + E[1]) / 2 - 4, '6', 11)]


