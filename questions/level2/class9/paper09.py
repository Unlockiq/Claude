def semicircle_cd():
    import math
    O, r = (120, 120), 104
    A, B = (O[0] - r, O[1]), (O[0] + r, O[1])
    D = (A[0] + 2 * r * 4 / 13, O[1])
    C = (D[0], O[1] - math.sqrt(r * r - (D[0] - O[0]) ** 2))
    arc = [(O[0] + r * math.cos(math.radians(a)), O[1] - r * math.sin(math.radians(a))) for a in range(0, 181, 6)]
    return [('polyline', arc), ('line', A[0], A[1], B[0], B[1]), ('line', C[0], C[1], D[0], D[1]),
            ('line', A[0], A[1], C[0], C[1]), ('line', B[0], B[1], C[0], C[1]),
            ('rect', D[0], D[1] - 8, 8, 8, None),
            ('text', A[0] - 10, A[1] + 6, 'A', 12), ('text', B[0] + 10, B[1] + 6, 'B', 12), ('text', C[0], C[1] - 12, 'C', 12),
            ('text', D[0], D[1] + 13, 'D', 12), ('text', (A[0] + D[0]) / 2, D[1] + 13, '4', 11), ('text', (D[0] + B[0]) / 2, D[1] + 13, '9', 11)]


